# Offline maintenance. Never recurse through links or delete runtimes/models.
function Resolve-AitMaintenancePath([string]$Root,[string]$Path) {
    $rootPath=[IO.Path]::GetFullPath($Root).TrimEnd('\')
    $full=[IO.Path]::GetFullPath($Path)
    if (-not $full.StartsWith($rootPath+'\',[StringComparison]::OrdinalIgnoreCase)) {throw 'AIT2-310: Путь вне служебной папки.'}
    Assert-AitOrdinaryPath $full
    return $full
}
function Test-AitMaintenanceOrdinary([string]$Path) {
    try{Assert-AitOrdinaryPath $Path;return $true}
    catch{if($_.Exception.Message -like 'AIT2-110:*'){return $false};throw}
}
function Add-AitStorageSkippedLink($Scan,[string]$Path) {
    if($null -ne $Scan){$Scan.links++;if($Scan.paths.Count -lt 50){$Scan.paths.Add($Path)}}
}
function Get-AitFileStamp($File,[string]$Relative) {
    $sha=[Security.Cryptography.SHA256]::Create()
    try{return ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($Relative+'|'+$File.Length+'|'+$File.LastWriteTimeUtc.Ticks+'|'+$File.CreationTimeUtc.Ticks)))).Replace('-','').ToLowerInvariant()}
    finally{$sha.Dispose()}
}
function Get-AitProcessingMediaKind([string]$Relative) {
    # Only exact names generated by our Lua/helper, in their two known locations.
    if($Relative -cmatch '^muscriptor_result_\d+\.(analysis|rendered)\.wav$' -or
       $Relative -cmatch '^(muscriptor_transcribe\\)?input_\d+(\.[a-zA-Z0-9_-]{6,16}\.part)?\.wav$' -or
       $Relative -cmatch '^(muscriptor_transcribe\\)?reaper_take_(\d+_\d+|[a-fA-F0-9]+)_\d+\.wav$'){return 'wav'}
    if($Relative -cmatch '^muscriptor_result_\d+\.mid(\.part)?$'){return 'midi'}
    return $null
}
function Read-AitProcessingMarker([string]$Path) {
    # A damaged/stale session record must never make the entire cleanup fail.
    try{return Read-AitJson $Path}catch{return $null}
}
function Test-AitProcessingSession([string]$Folder,[string]$CurrentInstance) {
    $id=[IO.Path]::GetFileName($Folder)
    if($id -notmatch '^[a-fA-F0-9]{32}$'){return $false}
    $markerPath=Join-Path $Folder 'session.json'
    if(-not (Test-AitMaintenanceOrdinary $markerPath)){return $false}
    $marker=Read-AitProcessingMarker $markerPath
    if(-not $marker -or $marker.schema -ne 1 -or $marker.owner -cne 'AiTranscriber2' -or $marker.id -cne $id){return $false}
    $updated=0L
    if(-not [long]::TryParse([string]$marker.updated,[ref]$updated)){return $false}
    $age=[DateTimeOffset]::UtcNow.ToUnixTimeSeconds()-$updated
    if($age -lt 0){return $false}
    # Old markers have no busy flag. Give a just-closed launcher time to write PID.
    $closed=$marker.closed -is [bool] -and $marker.closed
    $idle=$marker.busy -is [bool] -and -not $marker.busy
    if(-not (($closed -and ($idle -or $age -ge 60)) -or
       ($marker.closed -is [bool] -and -not $marker.closed -and $idle -and
        $id -ceq $CurrentInstance -and $age -le 90))){return $false}
    $pidPath=Join-Path $Folder 'muscriptor_helper.pid'
    if(-not (Test-AitMaintenanceOrdinary $pidPath)){return $false}
    if(Test-Path -LiteralPath $pidPath){
        if((Get-Item -LiteralPath $pidPath).Length -gt 32){return $false}
        $number=0
        if(-not [int]::TryParse([IO.File]::ReadAllText($pidPath).Trim(),[ref]$number) -or $number -le 0){return $false}
        if(Get-Process -Id $number -ErrorAction SilentlyContinue){return $false}
    }
    return $true
}
function Get-AitStorage([string]$StateRoot,$Active,[string]$CurrentInstance='') {
    $root=[IO.Path]::GetFullPath($StateRoot).TrimEnd('\');Assert-AitOrdinaryPath $root
    $tempRoot=Join-Path $root 'runtime_temp'
    $candidates=[Collections.Generic.List[object]]::new()
    $rows=@{wav=@{label='WAV для анализа';kind='wav';files=0;bytes=0L};midi=@{label='Временные MIDI';kind='midi';files=0;bytes=0L}}
    $scan=@{links=0;paths=[Collections.Generic.List[string]]::new()}
    $blocked=0;$blockedBytes=0L;$count=0
    # Component paths are guards only: never enumerate models, runtimes, jobs or caches.
    $protected=@($Active.python,$Active.mu_root,$Active.data_root)
    if($Active.weights){foreach($property in $Active.weights.PSObject.Properties){$protected+=@($property.Value)}}
    Write-AitEvent 'storage' 'Ищу временные WAV и MIDI…'
    if((Test-Path -LiteralPath $tempRoot) -and -not (Test-AitMaintenanceOrdinary $tempRoot)){Add-AitStorageSkippedLink $scan $tempRoot}
    elseif(Test-Path -LiteralPath $tempRoot -PathType Container){
      foreach($folder in Get-ChildItem -LiteralPath $tempRoot -Directory){
        Assert-AitNotCancelled
        if(++$count -gt 200000){throw 'AIT2-310: Слишком много файлов. Ничего не удалено.'}
        if($folder.Attributes -band [IO.FileAttributes]::ReparsePoint){Add-AitStorageSkippedLink $scan $folder.FullName;continue}
        if($folder.Name -notmatch '^[a-fA-F0-9]{32}$'){continue}
        [void](Resolve-AitMaintenancePath $root $folder.FullName)
        $markerPath=Join-Path $folder.FullName 'session.json'
        if(-not (Test-AitMaintenanceOrdinary $markerPath)){Add-AitStorageSkippedLink $scan $markerPath;continue}
        $marker=Read-AitProcessingMarker $markerPath
        if(-not $marker -or $marker.schema -ne 1 -or $marker.owner -cne 'AiTranscriber2' -or $marker.id -cne $folder.Name){continue}
        $eligible=Test-AitProcessingSession $folder.FullName $CurrentInstance
        foreach($location in @($folder.FullName,(Join-Path $folder.FullName 'muscriptor_transcribe'))){
          if(-not (Test-Path -LiteralPath $location -PathType Container)){continue}
          if(-not (Test-AitMaintenanceOrdinary $location)){Add-AitStorageSkippedLink $scan $location;continue}
          foreach($file in Get-ChildItem -LiteralPath $location -File){
            Assert-AitNotCancelled
            if(++$count -gt 200000){throw 'AIT2-310: Слишком много файлов. Ничего не удалено.'}
            if($file.Attributes -band [IO.FileAttributes]::ReparsePoint){Add-AitStorageSkippedLink $scan $file.FullName;continue}
            $relative=$file.FullName.Substring($folder.FullName.Length+1)
            $kind=Get-AitProcessingMediaKind $relative
            if(-not $kind){continue}
            [void](Resolve-AitMaintenancePath $root $file.FullName)
            $referenced=$false
            foreach($p in $protected){
              if($p -is [string] -and $p){$p=[IO.Path]::GetFullPath($p).TrimEnd('\')
                if($file.FullName.Equals($p,[StringComparison]::OrdinalIgnoreCase) -or $file.FullName.StartsWith($p+'\',[StringComparison]::OrdinalIgnoreCase)){$referenced=$true}
              }
            }
            if($referenced){continue}
            $rows[$kind].files++;$rows[$kind].bytes+=$file.Length
            if(-not $eligible){$blocked++;$blockedBytes+=$file.Length;continue}
            $relative=$file.FullName.Substring($root.Length+1)
            $candidates.Add(@{id=(Get-AitFileStamp $file $relative);path=$relative;bytes=$file.Length;kind=$kind;session_id=$folder.Name})
            if($candidates.Count -gt 5000){throw 'AIT2-310: Слишком много файлов. Ничего не удалено.'}
          }
        }
      }
    }
    return @{schema=2;created=[DateTimeOffset]::UtcNow.ToUnixTimeSeconds();path=$tempRoot;current_instance=$CurrentInstance;
      categories=@($rows.wav,$rows.midi);candidates=@($candidates.ToArray());blocked_files=$blocked;blocked_bytes=$blockedBytes;
      skipped_links=$scan.links;skipped_paths=@($scan.paths.ToArray())}
}
function Save-AitStoragePlan([string]$StateRoot,$Storage) {
    $Storage.plan_id=[guid]::NewGuid().ToString('N')
    $path=Join-Path $StateRoot 'storage_plan.json';Assert-AitOrdinaryPath $path;Assert-AitOrdinaryPath ($path+'.bak')
    Write-AitJson $path $Storage
    return $Storage
}
function Clear-AitStorage([string]$StateRoot,$Active,[string]$PlanId,$Selected,[string]$CurrentInstance='') {
    if($PlanId -notmatch '^[a-f0-9]{32}$' -or @($Selected).Count -lt 1 -or @($Selected).Count -gt 5000){throw 'AIT2-311: Сначала выберите файлы в свежем списке очистки.'}
    $path=Join-Path $StateRoot 'storage_plan.json';Assert-AitOrdinaryPath $path
    $plan=Read-AitJson $path
    if(-not $plan -or $plan.schema -ne 2 -or $plan.current_instance -cne $CurrentInstance -or $plan.plan_id -cne $PlanId -or [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()-[long]$plan.created -gt 1800){throw 'AIT2-311: Список устарел. Обновите список временных WAV и MIDI.'}
    # Recompute eligibility, ownership, activity, age and stamps before ANY delete.
    $fresh=Get-AitStorage $StateRoot $Active $CurrentInstance;$allowed=@{};$old=@{}
    foreach($entry in $fresh.candidates){$allowed[$entry.id]=$entry}
    foreach($entry in $plan.candidates){$old[$entry.id]=$entry}
    $targets=@(foreach($id in @($Selected|Select-Object -Unique)){
      if($id -isnot [string] -or $id -notmatch '^[a-f0-9]{64}$' -or -not $allowed.ContainsKey($id) -or -not $old.ContainsKey($id) -or $allowed[$id].path -cne $old[$id].path){throw 'AIT2-311: Файлы или состояние запуска изменились. Обновите список; ничего не удалено.'}
      $allowed[$id]
    })
    $bytes=0L;$deleted=0;$failed=0;$cancelled=$false
    foreach($entry in $targets){
      if($env:AIT2_CANCEL -and (Test-Path -LiteralPath $env:AIT2_CANCEL)){$cancelled=$true;break}
      try{
        $target=Resolve-AitMaintenancePath $StateRoot (Join-Path $StateRoot $entry.path)
        $session=Resolve-AitMaintenancePath $StateRoot (Join-Path $StateRoot ('runtime_temp\'+$entry.session_id))
        if(-not (Test-AitProcessingSession $session $CurrentInstance)){$failed++;continue}
        $file=Get-Item -LiteralPath $target
        if((Get-AitFileStamp $file $entry.path) -cne $entry.id){$failed++;continue}
        [IO.File]::Delete($target);$bytes+=$entry.bytes;$deleted++
      }catch{$failed++}
    }
    return @{deleted=$deleted;bytes=$bytes;failed=$failed;cancelled=$cancelled}
}
